class Command(BaseCommand):
    help = "Imports pilot genuine healthcare providers (Hospitals from data.gov.in and Pharmacies from OSM) with strict validation."

    def add_arguments(self, parser):
        parser.add_argument(
            '--dry-run',
            action='store_true',
            help='Run validation and report would-be imports without writing to database.',
        )
        parser.add_argument(
            '--include-invalid-test',
            action='store_true',
            help='Include intentionally invalid records to test validation and rejection pipeline.',
        )

    def handle(self, *args, **options):
        dry_run = options['dry_run']
        include_invalid = options['include_invalid_test']

        all_records = list(PILOT_GENUINE_HOSPITALS) + list(PILOT_GENUINE_PHARMACIES)
        if include_invalid:
            all_records.extend(INVALID_TEST_RECORDS)

        mode_str = "[DRY-RUN]" if dry_run else "[LIVE INGESTION]"
        self.stdout.write(self.style.WARNING(f"\n==> {mode_str} Starting MediFind Pilot Healthcare Provider Ingestion..."))
        self.stdout.write(f"    - Genuine Hospitals (data.gov.in): {len(PILOT_GENUINE_HOSPITALS)}")
        self.stdout.write(f"    - Genuine Pharmacies (OpenStreetMap): {len(PILOT_GENUINE_PHARMACIES)}")
        if include_invalid:
            self.stdout.write(f"    - Intentional Invalid Test Records: {len(INVALID_TEST_RECORDS)}")
        self.stdout.write(f"    - Total Records Scanned: {len(all_records)}\n")

        report = import_provider_records(all_records, dry_run=dry_run)

        self.stdout.write("--- INGESTION REPORT SUMMARY ---")
        self.stdout.write(self.style.SUCCESS(f"  Successfully Imported : {report.imported}"))
        self.stdout.write(self.style.WARNING(f"  Skipped (Duplicate)   : {report.skipped_duplicate}"))
        self.stdout.write(self.style.ERROR(f"  Rejected (Invalid)    : {report.rejected_invalid}"))
        self.stdout.write(f"  Total Processed       : {report.total_scanned}\n")

        for d in report.details:
            if "REJECTED" in d:
                self.stdout.write(self.style.ERROR(f"  [x] {d}"))
            elif "SKIPPED" in d:
                self.stdout.write(self.style.WARNING(f"  [-] {d}"))
            else:
                self.stdout.write(self.style.SUCCESS(f"  [+] {d}"))

        self.stdout.write(self.style.SUCCESS(f"\nExecution finished. Total providers in database: {Pharmacy.objects.count()} (Hospitals: {Pharmacy.objects.filter(provider_type='HOSPITAL').count()}, Pharmacies: {Pharmacy.objects.filter(provider_type='PHARMACY').count()})"))
